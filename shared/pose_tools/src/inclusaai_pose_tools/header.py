"""The pose-format ``PoseHeader`` for InclusaAI's 51-point sign skeleton.

The header describes *which* points exist and *how* they are grouped into
components — it is the pose-format counterpart of
``inclusaai_sign_vocab.skeleton.SKELETON``. Every ``Pose`` that flows through
InclusaAI (generated by avatar-pose, or extracted+subset by sign-recognition)
shares this one header, so the two sides line up point-for-point.

Point ``i`` of a frame corresponds to ``SKELETON[i]``. We group the flat
skeleton into three pose-format components — body, left hand, right hand — by
name prefix, so the component split stays derived from ``sign_vocab`` (single
source of truth) rather than hard-coded counts here.
"""

from __future__ import annotations

from functools import lru_cache

from inclusaai_sign_vocab.skeleton import NUM_KEYPOINTS, SKELETON
from pose_format.pose_header import (
    PoseHeader,
    PoseHeaderComponent,
    PoseHeaderDimensions,
)

#: 3 spatial dims (X, Y, Z); confidence (the ``C``) is stored separately by
#: pose-format in ``body.confidence``. Matches MediaPipe Holistic's format.
POINT_FORMAT = "XYZC"

_LEFT_PREFIX = "left_hand_"
_RIGHT_PREFIX = "right_hand_"


def _group(prefix: str | None) -> list[str]:
    if prefix is None:  # body = everything that is not a hand landmark
        return [n for n in SKELETON if not n.startswith((_LEFT_PREFIX, _RIGHT_PREFIX))]
    return [n for n in SKELETON if n.startswith(prefix)]


#: Component name → ordered point names, derived from SKELETON.
COMPONENTS: dict[str, list[str]] = {
    "body": _group(None),
    "left_hand": _group(_LEFT_PREFIX),
    "right_hand": _group(_RIGHT_PREFIX),
}


@lru_cache(maxsize=1)
def skeleton_header() -> PoseHeader:
    """Return the (cached) pose-format header for the 51-point sign skeleton."""
    components = [
        PoseHeaderComponent(
            name=name,
            points=list(points),
            limbs=[],  # connections are irrelevant to the wire contract / conversion
            colors=[(255, 255, 255)],  # one color keeps visualization code happy
            point_format=POINT_FORMAT,
        )
        for name, points in COMPONENTS.items()
    ]
    header = PoseHeader(
        version=0.2,
        dimensions=PoseHeaderDimensions(width=1, height=1, depth=1),
        components=components,
    )
    # Invariant: the header must describe exactly the shared skeleton.
    assert header.total_points() == NUM_KEYPOINTS, (
        f"skeleton_header has {header.total_points()} points, expected {NUM_KEYPOINTS}"
    )
    return header
